#!/usr/bin/env node
// Web bundle builder.
//
//   node tools/build-web.mjs                 -> production bundle in dist/www (used by the APK)
//   node tools/build-web.mjs --dev           -> same, unminified + sourcemaps
//   node tools/build-web.mjs --demo NAME     -> bundles src/dev/NAME.js into dist/dev/NAME/
//                                               (uses src/dev/NAME.html if present, else a default page)
//   node tools/build-web.mjs --out DIR       -> the app bundle into DIR instead of dist/www (private
//                                               builds while others work in the same tree; serve it to
//                                               the e2e scripts with E2E_WWW=DIR)
//
// Output layout (dist/www):
//   index.html  app.js  app.css  fonts.css  fonts/*.woff2   (+ ai-worker.js debug copy with --dev)
// Everything in dist/www ships inside the APK (tools/build-apk.sh), so nothing unused goes there:
// the worker is embedded in app.js, and web/static/icon-512.png (the 400 KB source of the launcher
// icon, which a WebView never shows as a favicon) stays in the repo only.
//
// The AI worker is bundled first and injected into app.js as the string constant
// __AI_WORKER_SRC__, so the app can start it from a Blob URL (works under any origin,
// including the Android WebView asset origin). Use `typeof __AI_WORKER_SRC__ !== 'undefined'`.
// The «Валькирии доски» battle AI worker (src/rpg/ai/worker.js) is injected the same way as
// __RPG_AI_WORKER_SRC__ (src/rpg/controller.js starts it; in-thread fallback without it).

import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const dev = args.includes('--dev');
const demoIdx = args.indexOf('--demo');
const demo = demoIdx >= 0 ? args[demoIdx + 1] : null;
const outIdx = args.indexOf('--out');
const outArg = outIdx >= 0 ? args[outIdx + 1] : null;

const TARGET = ['chrome87', 'es2020'];

// ---------------------------------------------------------------- fonts
// Fonts bundled with the game (woff2 only). family -> fontsource package + subsets.
const FONTS = [
  { pkg: 'dela-gothic-one', subsets: ['latin', 'latin-ext', 'cyrillic', 'japanese'] },
  { pkg: 'russo-one', subsets: ['latin', 'latin-ext', 'cyrillic'] },
  { pkg: 'oswald', subsets: ['latin', 'latin-ext', 'cyrillic'], weights: [400, 500, 700] },
  { pkg: 'unbounded', subsets: ['latin', 'latin-ext', 'cyrillic'], weights: [400, 700, 900] },
  { pkg: 'rubik-mono-one', subsets: ['latin', 'latin-ext', 'cyrillic'] },
];

function buildFonts(outDir) {
  const fontDir = path.join(outDir, 'fonts');
  fs.mkdirSync(fontDir, { recursive: true });
  let css = '/* generated by tools/build-web.mjs */\n';
  for (const f of FONTS) {
    const pkgDir = path.join(ROOT, 'node_modules/@fontsource', f.pkg);
    const weights = f.weights || [400];
    for (const sub of f.subsets) {
      for (const w of weights) {
        const cssFile = path.join(pkgDir, `${sub}-${w}.css`);
        if (!fs.existsSync(cssFile)) continue;
        let src = fs.readFileSync(cssFile, 'utf8');
        // keep woff2 only, copy referenced files
        src = src.replace(/src:\s*([^;]+);/g, (m, list) => {
          const woff2 = list.split(',').map((s) => s.trim()).find((s) => s.includes('.woff2'));
          const file = /url\(\.\/files\/([^)]+)\)/.exec(woff2)[1];
          fs.copyFileSync(path.join(pkgDir, 'files', file), path.join(fontDir, file));
          return `src: url(fonts/${file}) format('woff2');`;
        });
        src = src.replace(/font-display:\s*swap;/g, 'font-display: block;');
        css += src + '\n';
      }
    }
  }
  fs.writeFileSync(path.join(outDir, 'fonts.css'), css);
}

// ---------------------------------------------------------------- workers
async function buildWorker(rel = 'src/ai/worker.js') {
  const entry = path.join(ROOT, rel);
  if (!fs.existsSync(entry)) return '';
  const r = await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    format: 'iife',
    target: TARGET,
    minify: !dev,
    write: false,
    logLevel: 'warning',
  });
  return r.outputFiles[0].text;
}

// ---------------------------------------------------------------- app
async function buildApp({ entry, outDir, html, workerSrc, rpgWorkerSrc }) {
  fs.mkdirSync(outDir, { recursive: true });
  await esbuild.build({
    entryPoints: { app: entry },
    bundle: true,
    format: 'iife',
    target: TARGET,
    minify: !dev,
    sourcemap: dev ? 'inline' : false,
    outdir: outDir,
    loader: { '.png': 'dataurl', '.svg': 'text', '.woff2': 'file', '.glsl': 'text', '.frag': 'text', '.vert': 'text' },
    define: {
      __AI_WORKER_SRC__: JSON.stringify(workerSrc || ''),
      __RPG_AI_WORKER_SRC__: JSON.stringify(rpgWorkerSrc || ''),
      __DEV__: JSON.stringify(dev),
    },
    logLevel: 'warning',
  });
  buildFonts(outDir);
  // readable copy of the embedded worker, for debugging only (never shipped)
  if (workerSrc && (dev || demo)) fs.writeFileSync(path.join(outDir, 'ai-worker.js'), workerSrc);
  if (rpgWorkerSrc && (dev || demo)) fs.writeFileSync(path.join(outDir, 'rpg-ai-worker.js'), rpgWorkerSrc);
  fs.writeFileSync(path.join(outDir, 'index.html'), html);
}

/** web/static files that are NOT copied into dist/www (kept in the repo for other tools). */
const STATIC_SKIP = new Set(['icon-512.png']);

const DEFAULT_DEMO_HTML = (name) => `<!doctype html>
<html lang="ru"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">
<title>${name}</title>
<link rel="stylesheet" href="fonts.css"><link rel="stylesheet" href="app.css">
<style>html,body{margin:0;height:100%;background:#000;color:#fff;overflow:hidden}</style>
</head><body><div id="app"></div><script src="app.js"></script></body></html>`;

const t0 = Date.now();
const workerSrc = await buildWorker();
const rpgWorkerSrc = await buildWorker('src/rpg/ai/worker.js');
if (demo) {
  const entry = path.join(ROOT, 'src/dev', `${demo}.js`);
  const htmlFile = path.join(ROOT, 'src/dev', `${demo}.html`);
  const html = fs.existsSync(htmlFile) ? fs.readFileSync(htmlFile, 'utf8') : DEFAULT_DEMO_HTML(demo);
  const outDir = path.join(ROOT, 'dist/dev', demo);
  await buildApp({ entry, outDir, html, workerSrc, rpgWorkerSrc });
  // app.css may not exist if the demo imports no CSS; create an empty one so the link resolves
  if (!fs.existsSync(path.join(outDir, 'app.css'))) fs.writeFileSync(path.join(outDir, 'app.css'), '');
  console.log(`demo ${demo} -> ${path.relative(ROOT, outDir)} (${Date.now() - t0} ms)`);
} else {
  const outDir = outArg ? path.resolve(outArg) : path.join(ROOT, 'dist/www');
  if (outArg && (outDir === ROOT || outDir === path.parse(outDir).root)) throw new Error(`refusing to build into ${outDir}`);
  fs.rmSync(outDir, { recursive: true, force: true });
  const html = fs.readFileSync(path.join(ROOT, 'web/index.html'), 'utf8');
  await buildApp({ entry: path.join(ROOT, 'src/main.js'), outDir, html, workerSrc, rpgWorkerSrc });
  if (!fs.existsSync(path.join(outDir, 'app.css'))) fs.writeFileSync(path.join(outDir, 'app.css'), '');
  // static extras (icons etc.)
  const extra = path.join(ROOT, 'web/static');
  if (fs.existsSync(extra)) {
    fs.cpSync(extra, outDir, { recursive: true, filter: (src) => !STATIC_SKIP.has(path.relative(extra, src)) });
  }
  console.log(`app -> ${path.relative(ROOT, outDir)} (${Date.now() - t0} ms)`);
}
