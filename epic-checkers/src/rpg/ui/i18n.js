export const RPG_TABLES = { ru: RU, en: EN };

function lookup(table, key) {
  let v = table;
  for (const part of key.split('.')) {
    if (v == null || typeof v !== 'object') return undefined;
    v = v[part];
  }
  return v;
}

function interpolate(str, params) {
  if (!params) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? String(params[k]) : m));
}

/** Translated UI string (falls back to Russian, then to the key). */
export function rt(key, params) {
  const lang = getLang();
  let v = lookup(RPG_TABLES[lang] || RU, key);
  if (v == null) v = lookup(RU, key);
  if (v == null) return key;
  if (Array.isArray(v)) v = v.join('\n');
  else if (typeof v === 'object') {
    const n = params && (params.n ?? params.count);
    const cat = pluralCategory(n, lang);
    v = v[cat] ?? v.other ?? v.many ?? v.one ?? '';
  }
  return interpolate(String(v), params);
}

/** Array strings (paragraph lists). */
export function rtList(key, params) {
  const lang = getLang();
  let v = lookup(RPG_TABLES[lang] || RU, key);
  if (v == null) v = lookup(RU, key);
  if (v == null) return [];
  return (Array.isArray(v) ? v : [v]).map((s) => interpolate(String(s), params));
}

/** Localised data string ({ ru, en, jp? } objects of src/rpg/data). */
export function L(obj) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  const lang = getLang();
  return obj[lang] ?? obj.ru ?? obj.en ?? '';
}

/** Localised list ({ ru: [...], en: [...] }). */
export function LL(obj) {
  if (!obj) return [];
  const v = obj[getLang()] ?? obj.ru ?? obj.en;
  return Array.isArray(v) ? v : v ? [v] : [];
}

/** Numbers with thin spaces between thousands (3 200), as in the GDD. */
export function fmt(n) {
  const v = Math.round(Number(n) || 0);
  const s = String(Math.abs(v)).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
  return (v < 0 ? '−' : '') + s;
}
